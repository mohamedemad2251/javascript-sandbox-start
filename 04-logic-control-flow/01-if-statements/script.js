// If statements are used to execute code if a condition is true.

if (true) {
    console.log("This will be executed");
}

if (false) {
    console.log("This will not be executed");
}

if (10 > 5) {
    console.log("This will be executed");
}

if (10 < 5) {
    console.log("This will not be executed");
}

// If statements can have an else statement.
if (10 > 5) {
    console.log("This will be executed");
}
else {
    console.log("This will not be executed");
}

// Remember, === is the strict equality operator. It checks if the value and the type are the same. Same as !==.
if (10 === 10) {
    console.log("This will be executed");
}

