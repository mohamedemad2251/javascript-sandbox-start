// To do an else if:
const x = 5;
if (x > 5) {
    console.log(`x is bigger than 5`);
}
else if (x === 5) {
    console.log(`x is equal to 5`);
}
else {
    console.log(`x is less than 5`);
}

// Of course, the if conditionals: if...else if...else is executed sequentially, so once a condition is satisfied, the rest after it is ignored.

